# exponents in python
base = 2
exponent = 3
result = base**exponent
print(result)

# assignment operators
x = 5
x += 1
x -= 1
x *= 2
x /= 2
print(x)

# Scientific notation
x = 1.23e3
print(x)

# logical operators
x = True
y = False
print(x and y)
print(x or y)
print(not x)

# bitwise operators
binary_one = 0b1010
binary_two = 0b0101
print(binary_one & binary_two)
